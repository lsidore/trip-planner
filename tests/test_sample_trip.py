import datetime as dt
import glob
import json
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import tripctx  # noqa: E402

SAMPLE = os.path.join(ROOT, "examples", "sample-trip")
RES = os.path.join(SAMPLE, "research")
STAGES = ("lisbon", "comporta", "porto")
# Real Wikimedia Commons credits, not invented data: exempt from the "_example" marker.
REAL_DATA = {"photo-credits.json"}


# Standard UTC offsets (June 2027: daylight saving everywhere) for the airports used in the raw flights.
UTC_OFFSET_H = {"JFK": -4, "YUL": -4, "LIS": 1, "OPO": 1, "MAD": 2, "CDG": 2}


def utc(airport, local_iso):
    return dt.datetime.fromisoformat(local_iso) - dt.timedelta(hours=UTC_OFFSET_H[airport])


def read(*parts):
    with open(os.path.join(RES, *parts), encoding="utf-8") as f:
        return json.load(f)


def all_json():
    # vols-options.json is generated by flights.py / page_data.py, not sample data
    return sorted(p for p in glob.glob(os.path.join(RES, "**", "*.json"), recursive=True) if os.path.basename(p) != "vols-options.json")


class SampleTripTests(unittest.TestCase):
    def test_every_research_file_parses(self):
        files = all_json()
        self.assertGreaterEqual(len(files), 25)
        for p in files:
            with self.subTest(p=os.path.relpath(p, RES)):
                read(os.path.relpath(p, RES))

    def test_ids_prefixed_by_stage(self):
        for s in STAGES:
            for o in read(f"logements-{s}.json"):
                self.assertTrue(o["id"].startswith(s + "-"), o["id"])
                self.assertEqual(o["etape"], s)
            for sid in read(f"sorties-{s}.json"):
                self.assertTrue(sid.startswith(s + "-"), sid)

    def test_each_stage_has_three_lodgings_and_a_fiche(self):
        fiches = {f["id"] for f in read("resorts-fiches-sample.json")}
        self.assertEqual(len(fiches), 3)
        for s in STAGES:
            lodgings = read(f"logements-{s}.json")
            self.assertEqual(len(lodgings), 3, s)
            ids = [o["id"] for o in lodgings]
            self.assertEqual(len(set(ids)), 3)
            self.assertEqual(len([i for i in ids if i in fiches]), 1, s)
            for o in lodgings:
                self.assertTrue(1 <= len(o["photo_urls"]) <= 3, o["id"])
                self.assertTrue(all(u.startswith("https://upload.wikimedia.org/") for u in o["photo_urls"]))
        for f in read("resorts-fiches-sample.json"):
            self.assertIsInstance(f["cout_reel"], dict)

    def test_last_transport_and_special_present(self):
        acces = read("acces-logements.json")
        self.assertEqual(acces["comporta-01"]["dernier_public"], "20:30")
        self.assertEqual(acces["comporta-01"]["mode"], "voiture+bateau")
        for fid in (f["id"] for f in read("resorts-fiches-sample.json")):
            self.assertIn(fid, acces)
        special = [k for k, v in read("sorties-porto.json").items() if v.get("speciale") == "sao-joao"]
        self.assertEqual(len(special), 2)
        gala = [f for f in read("resorts-fiches-sample.json") if f["id"].startswith("porto-")]
        self.assertEqual(gala[0]["gala_pour"], "sao-joao")
        self.assertTrue(gala[0]["gala"])
        for s in STAGES:
            self.assertIn(len(read(f"sorties-{s}.json")), (3, 4))

    def test_every_sortie_has_a_place(self):
        for s in STAGES:
            ids = {p["id"] for n in ("restos", "activites") for p in read(f"lieux-{s}-{n}.json")["pois"]}
            ids |= {p["id"] for p in read("lieux-agenda.json")["pois"] if p["etape"] == s}
            self.assertTrue(set(read(f"sorties-{s}.json")) <= ids, s)
        for p in read("lieux-agenda.json")["pois"]:
            self.assertIn(p["etape"], STAGES)

    def test_raw_flights_for_every_flight_leg(self):
        trip = tripctx.load(SAMPLE)
        legs = [l for l in trip.legs if l["mode"] == "flight"]
        self.assertEqual(len(legs), 5)
        for l in legs:
            name = f"{l['key']}-{l['date'].replace('-', '')}.json"
            raw = read("vols-brut", name)
            self.assertTrue(2 <= len(raw["itineraries"]) <= 3, name)
            self.assertEqual(raw["_requete"]["flyFrom"], l["from_airports"][0])
            self.assertEqual(raw["_requete"]["flyTo"], l["to_airports"][0])
            for it in raw["itineraries"]:
                self.assertIn("checkedBag", it["baggage"])
                self.assertEqual(it["outbound"]["segments"][0]["from"], l["from_airports"][0])
                self.assertEqual(it["outbound"]["segments"][-1]["to"], l["to_airports"][0])
                segs = it["outbound"]["segments"]
                for a, b in zip(segs, segs[1:]):
                    layover = utc(b["from"], b["departureTime"]) - utc(a["to"], a["arrivalTime"])
                    self.assertGreaterEqual(layover, dt.timedelta(minutes=45), (name, a["to"]))
                    self.assertEqual(a["to"], b["from"])
                for sg in segs:
                    span = utc(sg["to"], sg["arrivalTime"]) - utc(sg["from"], sg["departureTime"])
                    self.assertEqual(span.total_seconds(), sg["durationSeconds"], (name, sg["flightNumber"]))
                real = (utc(segs[-1]["to"], segs[-1]["arrivalTime"]) - utc(segs[0]["from"], segs[0]["departureTime"])).total_seconds()
                self.assertEqual(it["totalDurationSeconds"], real, name)
                self.assertEqual(it["outbound"]["durationSeconds"], real, name)
                self.assertEqual(it["outbound"]["stops"], len(segs) - 1)

    def test_ground_leg_options(self):
        t = [x for x in read("trajets.json")["trajets"] if x["date"] == "2027-06-18"]
        self.assertEqual(len(t), 1)
        self.assertEqual(len(t[0]["options"]), 2)
        for o in t[0]["options"]:
            self.assertIsInstance(o["prix_couple_home"], (int, float))

    def test_formalities_cover_travelers(self):
        f = read("formalites.json")
        self.assertEqual({x["qui"] for x in f}, {"a", "b", "all"})
        self.assertTrue(any(x["qui"] == "all" and x["cout_home"] > 0 for x in f))
        self.assertEqual(read("taux.json"), {"_example": True, "taux": 0.92, "date": "2026-11-07",
                                             "source": "EXAMPLE — invented"})

    def test_cost_units_match_fiches(self):
        units = read("couts-unites.json")
        for f in read("resorts-fiches-sample.json"):
            lines = units[f["id"]]
            for poste, rows in lines.items():
                total = sum(r["n"] * r["u"] for r in rows)
                self.assertLessEqual(abs(total - f["cout_reel"][poste]), 1.5, f"{f['id']} {poste}")
        self.assertEqual(set(units), {f["id"] for f in read("resorts-fiches-sample.json")})

    def test_photo_credits_cover_photos(self):
        credits = read("photo-credits.json")
        used = {u for s in STAGES for o in read(f"logements-{s}.json") for u in o["photo_urls"]}
        self.assertEqual(used, set(credits))
        for c in credits.values():
            self.assertTrue(c["author"] and c["license"] and c["source_page"].startswith("https://commons.wikimedia.org/"))
            self.assertRegex(c["license"], r"^(CC0|CC BY|CC BY-SA)")

    def test_dates_inside_stage_ranges(self):
        trip = tripctx.load(SAMPLE)
        rng = {s["key"]: (s["from"], s["to"]) for s in trip.stages}
        for s in STAGES:
            for o in read(f"logements-{s}.json"):
                self.assertEqual((o["checkin"], o["checkout"]), rng[s])
            for p in read(f"lieux-{s}-restos.json")["pois"] + read(f"lieux-{s}-activites.json")["pois"]:
                for d in p.get("dates", []):
                    self.assertTrue(rng[s][0] <= d <= rng[s][1], (p["id"], d))
            for k, v in read(f"sorties-{s}.json").items():
                if v["date_fixe"]:
                    self.assertTrue(rng[s][0] <= v["date_fixe"] <= rng[s][1], k)
        for p in read("lieux-agenda.json")["pois"]:
            for d in p["dates"]:
                self.assertTrue(rng[p["etape"]][0] <= d <= rng[p["etape"]][1], p["id"])

    def test_everything_marked_example(self):
        for p in all_json():
            rel = os.path.relpath(p, RES)
            if os.path.basename(p) in REAL_DATA:
                continue
            d = read(rel)
            name = os.path.basename(p)
            with self.subTest(file=rel):
                if rel.startswith("vols-brut") or name == "taux.json":
                    self.assertIs(d.get("_example"), True)
                elif name == "trajets.json":
                    self.assertIs(d["meta"].get("_example"), True)
                    self.assertTrue(all(t.get("_example") is True for t in d["trajets"]))
                elif name == "couts-unites.json":
                    rows = [r for postes in d.values() for lines in postes.values() for r in lines]
                    self.assertTrue(rows and all(r.get("_example") is True for r in rows))
                elif isinstance(d, list):
                    self.assertTrue(d and all(x.get("_example") is True for x in d))
                elif "pois" in d:
                    self.assertTrue(d["pois"] and all(x.get("_example") is True for x in d["pois"]))
                else:  # id-keyed dict (acces-logements, sorties-*, logements-exclus)
                    self.assertNotIn("_example", d)
                    self.assertTrue(d and all(v.get("_example") is True for v in d.values()))

    def test_markdown_files_marked(self):
        for n in ("profile", "guide", "stays", "transport", "activities", "itinerary", "budget", "checklist"):
            with open(os.path.join(SAMPLE, n + ".md"), encoding="utf-8") as f:
                self.assertTrue(f.read().lstrip().split("\n", 1)[0].startswith("# EXAMPLE — invented data"), n)


if __name__ == "__main__":
    unittest.main()
